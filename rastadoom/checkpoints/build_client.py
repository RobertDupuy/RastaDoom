#!/usr/bin/env python3
"""Build fixed-ROM diagnostic CAR and the matching engine header. No emulator."""
from pathlib import Path
import argparse, hashlib, json, re, struct, subprocess

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
p=argparse.ArgumentParser()
p.add_argument('--base-uf2',type=Path,required=True)
a=p.parse_args()
raw=a.base_uf2.read_bytes()
assert hashlib.sha256(raw).hexdigest()=='3364a0ba142b59790bc6f16f0ceacd2a63616e6e4869fa44a1e4ec18f17e9789'
flash=bytearray(b'\xff'*0x1000000)
for pos in range(0,len(raw),512):
    h=struct.unpack_from('<8I',raw,pos)
    assert h[0:2]==(0x0a324655,0x9e5d5157) and h[4]==256
    off=h[3]-0x10000000
    flash[off:off+256]=raw[pos+32:pos+288]
original=flash[0x13428:0x134b0]
assert len(original)==136 and original[:8].hex()=='d0238022f0b5ce46'
assert original[0x3a:0x3c]==bytes.fromhex('fad0')
assert struct.unpack_from('<I',original,0x84)[0]==0x20005cc0
(HERE/'original_loop.h').write_text('/* Robin Edwards original standard-16K handler, supplied UF2. */\nstatic const unsigned char original_loop[136]={\n'+','.join(str(x) for x in original)+'};\n')

messages=[
 'STEP 1 - CARTRIDGE RUNNING', 'STEP 2 - ATARI CLIENT READY',
 'STEP 3 - STARTING PICO DOOM', 'STEP 4 - PICO RESPONDING',
 'STEP 5 - DOOM INITIALIZED', 'STEP 6 - FIRST FRAME READY',
 'STEP 7 - FRAME SELECTED', 'STEP 8 - ENTERING RASTER CODE',
 'STEP 9 - FIRST FRAME COMPLETED']
errors={'err_link':'STOPPED - NO PICO ACKNOWLEDGEMENT',
        'err_init':'STOPPED - DOOM INIT DID NOT COMPLETE',
        'err_frame':'STOPPED - NO COMPLETE FRAME',
        'err_select':'STOPPED - FRAME NOT SELECTED'}
def row(label,text):
    assert len(text)<=40
    return f'{label}: .byte "{text:<40}"\n'
(HERE/'messages.inc').write_text('message_lo: .lobytes '+','.join(f'msg{i}' for i in range(1,10))+'\nmessage_hi: .hibytes '+','.join(f'msg{i}' for i in range(1,10))+'\n'+''.join(row(f'msg{i}',text) for i,text in enumerate(messages,1)))
(HERE/'errors.inc').write_text(''.join(row(k,v) for k,v in errors.items()))
dl=[]
for y in range(192):
    addr=0x8000+y*40+(16 if y>=102 else 0)
    dl.append(f'.byte $4e\n.word ${addr:04x}' if y in (0,102) else '.byte $0e')
(HERE/'game_list.inc').write_text('\n'.join(dl)+'\n')
build=ROOT/'build-steps';build.mkdir(exist_ok=True)
for name in ['client','boot']:
    subprocess.run(['ca65',str(HERE/f'{name}.s'),'-I',str(HERE),'-o',str(build/f'{name}.o')],cwd=HERE,check=True)
    subprocess.run(['ld65','-C',str(HERE/f'{name}.cfg'),str(build/f'{name}.o'),'-o',str(build/f'{name}.bin'),'-Ln',str(build/f'{name}.lbl'),'-m',str(build/f'{name}.map')],check=True)
client=(build/'client.bin').read_bytes();rom=bytearray((build/'boot.bin').read_bytes())
assert len(client)==4096 and len(rom)==16384
rom[:4096]=client
labels={}
for line in (build/'client.lbl').read_text().splitlines():
    _,address,name=line.split();labels[name.lstrip('.')]=int(address,16)
assert 0x2000<=labels['frame_end']<0x2700
assert struct.unpack_from('<H',rom,0x3ffa)[0]==0xa000
assert rom[0x3ffc:0x4000]==bytes.fromhex('0004f0bf')
out=ROOT/'dist/steps-0.5.0';out.mkdir(parents=True,exist_ok=True)
(out/'DOOMSTEP.CAR').write_bytes(b'CART'+struct.pack('>III',2,sum(rom)&0xffffffff,0)+rom)
(build/'steps.rom').write_bytes(rom)
header=f'/* Generated by checkpoints/build_client.py. */\n#define RD_CLIENT_FRAME_END 0x{labels["frame_end"]:04x}\nstatic const unsigned char rd_boot_rom[16384]={{\n'
header+='\n'.join(','.join(str(x) for x in rom[i:i+32])+',' for i in range(0,len(rom),32))+'\n};\n'
(HERE.parent/'firmware/client_rom.h').write_text(header)
(out/'client-build.json').write_text(json.dumps({'car_type':2,'rom_bytes':len(rom),'run_vector':'0xa000','init_vector':'0xbff0','flags':4,'labels':labels,'car_sha256':hashlib.sha256((out/'DOOMSTEP.CAR').read_bytes()).hexdigest(),'messages':messages},indent=2)+'\n')
print(json.dumps({'rom_bytes':len(rom),'client_bytes':len(client),'labels':labels,'car':str(out/'DOOMSTEP.CAR')}))
